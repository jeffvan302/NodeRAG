import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const serverRequire = createRequire(
  resolve(import.meta.dirname, '../packages/server/package.json'),
);

const fonts = {
  notoCyrillic: 'noto-sans-cyrillic-400-normal.woff',
  notoDevanagari: 'noto-sans-devanagari-400-normal.woff',
  notoGreek: 'noto-sans-greek-400-normal.woff',
  notoLatin: 'noto-sans-latin-400-normal.woff',
  notoLatinBold: 'noto-sans-latin-700-normal.woff',
  notoLatinItalic: 'noto-sans-latin-400-italic.woff',
  notoLatinExtended: 'noto-sans-latin-ext-400-normal.woff',
  notoVietnamese: 'noto-sans-vietnamese-400-normal.woff',
};

const declarations = [];
for (const [name, file] of Object.entries(fonts)) {
  const path = serverRequire.resolve(`@fontsource/noto-sans/files/${file}`);
  const bytes = await readFile(path);
  declarations.push(`export const ${name} = Buffer.from('${bytes.toString('base64')}', 'base64');`);
}

const output = [
  '// Generated by scripts/generate-chat-font-assets.mjs from @fontsource/noto-sans@5.3.0.',
  '// The embedded subsets are licensed under OFL-1.1; see THIRD-PARTY.md.',
  '',
  ...declarations,
  '',
].join('\n');

await writeFile(
  resolve(import.meta.dirname, '../packages/server/src/chat/generated-fonts.ts'),
  output,
);
